def money(v: float) -> str:
    r = int(Decimal(v).quantize(Decimal(1), rounding=ROUND_HALF_UP))  # as Excel rounds, so page and sheet agree
    if r == 0:
        return "–"
    s = f"${abs(r):,}"
    return f"({s})" if r < 0 else s


def pct(v: float) -> str:
    s = f"{abs(v) * 100:.1f}%"
    return f"({s})" if v < 0 else s


