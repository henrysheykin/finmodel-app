def money(v: float) -> str:
    r = round(v)
    if r == 0:
        return "–"
    s = f"${abs(r):,}"
    return f"({s})" if r < 0 else s


def pct(v: float) -> str:
    s = f"{abs(v) * 100:.1f}%"
    return f"({s})" if v < 0 else s


def fmt_input(v: float, fmt: str) -> str:
    if fmt == "pct":
        return f"{v * 100:.1f}".rstrip("0").rstrip(".") + "%"
    if fmt == "usd2":
        return f"${v:,.2f}"
    if fmt == "usd":
        return f"${v:,.0f}"
    if fmt == "dec1":
        return f"{v:,.1f}".rstrip("0").rstrip(".")
    return f"{v:,.0f}"


def _row(label: str, cells: list[str], kind: str = "", ticks: bool = False, on: int | None = None) -> dict:
    return {
        "label": label,
        "kind": kind,
        "cells": [{"v": c, "tick": ticks, "on": on == i} for i, c in enumerate(cells)],
    }


def _by_label(rows: list[dict]) -> dict[str, list]:
    return {r["label"]: r["values"] for r in rows}


@lru_cache(maxsize=1)
def sheet_data() -> dict:
    return json.loads(DATA.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def sheet_views() -> dict:
    """Every case × tab view, ready to render (the page script only swaps them)."""
    d = sheet_data()
    years = [f"Year {i + 1}" for i in range(d["years"])]
    views: dict[str, dict[str, dict]] = {}
    for case, sc in d["scenarios"].items():
        summary, pl = _by_label(sc["summary"]), _by_label(sc["pl"])
        idx = int(case) - 1

        def lines(spec, source):
            out = [_row("", years, "head")]
            for label, kind, tick in spec:
                vals = source[label]
                cells = [pct(v) for v in vals] if kind == "pct" else [money(v) for v in vals]
                out.append(_row(label, cells, kind, tick))
            return out

        inputs = [_row("", ["Low", "Base", "High"], "head")] + [
            _row(i["label"], [fmt_input(v, i["fmt"]) for v in i["values"]], "input", on=idx) for i in d["inputs"]
        ]
        checks = [{"label": "Check", "kind": "head", "chk": True, "result": "Result", "what": "What it tests"}]
        for c in sc["checks"]:
            verdict = c["label"] == "Overall verdict"
            checks.append(
                {
                    "label": c["label"],
                    "kind": "total" if verdict else "",
                    "chk": True,
                    "result": c["result"],
                    "warn": c["result"] != "PASS",
                    "what": c["what"] or ("All checks above" if verdict else ""),
                }
            )
        views[case] = {
            "sum": {"rows": lines(SUMMARY_ROWS, summary), **d["formulas"]["sum"]},
            "inp": {"rows": inputs, **d["formulas"]["inp"]},
            "pl": {"rows": lines(PL_ROWS, pl), **d["formulas"]["pl"]},
            "chk": {"rows": checks, **d["formulas"]["chk"]},
        }
    return views


