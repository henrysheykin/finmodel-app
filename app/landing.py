@router.get("/samples/{slug}.xlsx", include_in_schema=False)
def sample(slug: str) -> FileResponse:
    """/samples/<key>.xlsx (landing alias of <key>-full) or any named sample, e.g. /samples/cafe-full-5y.xlsx."""
    if slug in SAMPLE_FILES:
        fname = SAMPLE_FILES[slug][0]
    elif (spec := parse_name(slug)) is not None:
        fname = spec.filename
    else:
        raise HTTPException(404, "not found")
    path = SAMPLES / fname
    if not path.is_file():
        raise HTTPException(404, "not found")
    return FileResponse(
        path,
        media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        filename=f"startupmodel-sample-{slug}.xlsx",
        headers={"Cache-Control": "public, max-age=3600"},
    )


@router.get("/preview/workbook.json", include_in_schema=False)
def preview_workbook(v: str = "") -> FileResponse:
    """The hero spreadsheet's data; the page links it with a content hash, so it can be cached for good."""
    fresh = v == xlview.workbook_version()
    return FileResponse(
        xlview.DATA,
        media_type="application/json",
        headers={"Cache-Control": "public, max-age=31536000, immutable" if fresh else "no-cache"},
    )


@router.get("/robots.txt", include_in_schema=False)
def robots(request: Request) -> PlainTextResponse:
    base = request.app.state.services.cfg.public_base_url
    lines = ["User-agent: *", "Allow: /"]
    for path in ("/admin", "/account", "/checkout/", "/login", "/download/", "/api/", "/dev/"):
        lines.append(f"Disallow: {path}")
    lines += ["", f"Sitemap: {base}/sitemap.xml", ""]
    return PlainTextResponse("\n".join(lines))


@router.get("/sitemap.xml", include_in_schema=False)
def sitemap(request: Request) -> Response:
    base = request.app.state.services.cfg.public_base_url
    paths = ["/"] + seo.sitemap_paths() + [f"/{p}" for p in LEGAL_PAGES if (LEGAL / f"{p}.md").is_file()]
    urls = "".join(f"<url><loc>{html.escape(base + p)}</loc></url>" for p in paths)
    xml = f'<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{urls}</urlset>'
    return Response(xml, media_type="application/xml")


