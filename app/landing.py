def legal_html(md: str) -> str:
    """Markdown subset for legal texts: #/##/### headings, paragraphs, lists, **bold**, [links](url)."""
    out = []
    for block in re.split(r"\n\s*\n", md.strip()):
        m = re.match(r"^(#{1,3})\s+(.*)$", block.strip())
        if m and "\n" not in block.strip():
            level = min(len(m.group(1)) + 1, 3)  # the page title is the only h1
            out.append(f"<h{level}>{html.escape(m.group(2))}</h{level}>")
        else:
            out.append(md_to_html(html.escape(block, quote=False)))
    return "\n".join(out)


def legal(page: str, request: Request) -> HTMLResponse:
    cfg = request.app.state.services.cfg
    path = LEGAL / f"{page}.md"
    body = legal_html(path.read_text(encoding="utf-8")) if path.is_file() else None
    return templates.TemplateResponse(
        request,
        "legal.html",
        {
            "title": LEGAL_PAGES[page],
            "body": Markup(body) if body else None,
            "support_email": cfg.support_email,
            "base_url": cfg.public_base_url,
            "page": page,
        },
    )


